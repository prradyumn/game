#!/usr/bin/env node
/* Re-encode the game's art as WebP, downscaled to what the game actually displays.
   Sources: _source-art/assets/** (full-res originals, git-ignored). Output: assets/**.webp
   plus js/asset-sizes.js (logical sizes stay those of the originals, so layout maths is unchanged).
   Uses headless Chrome's WebP encoder via Playwright (no native image tools needed).

   node tools/optimize-assets.js [--quality 0.84] [--chrome /path/to/chrome]
   Keys listed in USED (below) are shipped; everything else stays only in _source-art. */
'use strict';
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, '_source-art', 'assets');
const OUT = path.join(ROOT, 'assets');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const QUALITY = +opt('quality', 0.84);

// Longest-side cap (px) per asset, matched in order; null = keep native size.
// Caps are ~2x the largest on-screen size so they stay sharp on retina displays.
const CAPS = [
  [/^fx\/confetti\//, 96],
  [/^fx\/effects\//, 200],
  [/^background\/birds\//, 240],
  [/^background\/atmosphere\/(fish|pollen)/, 260],
  [/^background\/atmosphere\/(cloud|seaweed)/, 420],
  [/^background\/atmosphere\/ray/, 480],
  [/^dice\/(digits|sign-kit\/(plus|minus)-face)/, 320],
  [/^tokens\/.*-parts\/mini-head$/, 128],
  [/^textures\/paper-grain$/, 600],
  [/^ui\/icons\//, 160],
  [/^ui\/logo\/app-icon-64$/, null],
  [/./, null]
];
const QUALITY_FOR = k => /^(background\/(desktop|phone)|ui\/screens\/start-backdrop|board\/world-aligned)$/.test(k) ? 0.8 : QUALITY;

const USED = JSON.parse(fs.readFileSync(path.join(__dirname, 'used-assets.json'), 'utf8'));

function findSource(key) {
  for (const ext of ['png', 'jpg', 'jpeg']) { const f = path.join(SRC, `${key}.${ext}`); if (fs.existsSync(f)) return f; }
  throw new Error('missing source for ' + key);
}

(async () => {
  const b = await chromium.launch(opt('chrome') ? { executablePath: opt('chrome') } : {});
  const p = await b.newPage();
  const sizes = {};
  let before = 0, after = 0;
  for (const key of USED) {
    const file = findSource(key);
    const buf = fs.readFileSync(file);
    before += buf.length;
    const cap = CAPS.find(([re]) => re.test(key))[1];
    const mime = file.endsWith('png') ? 'image/png' : 'image/jpeg';
    const res = await p.evaluate(async ({ data, cap, q }) => {
      const img = new Image(); img.src = data; await img.decode();
      const W = img.naturalWidth, H = img.naturalHeight;
      const k = cap ? Math.min(1, cap / Math.max(W, H)) : 1;
      const w = Math.max(1, Math.round(W * k)), h = Math.max(1, Math.round(H * k));
      const c = document.createElement('canvas'); c.width = w; c.height = h;
      const ctx = c.getContext('2d'); ctx.imageSmoothingEnabled = true; ctx.imageSmoothingQuality = 'high';
      ctx.drawImage(img, 0, 0, w, h);
      const blob = await new Promise(r => c.toBlob(r, 'image/webp', q));
      const bytes = new Uint8Array(await blob.arrayBuffer());
      let s = ''; for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
      return { W, H, w, h, b64: btoa(s) };
    }, { data: `data:${mime};base64,${buf.toString('base64')}`, cap, q: QUALITY_FOR(key) });
    const out = path.join(OUT, key + '.webp');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const webp = Buffer.from(res.b64, 'base64');
    fs.writeFileSync(out, webp);
    after += webp.length;
    sizes[key] = [res.W, res.H, 'webp'];          // logical size = original pixels
    if (res.w !== res.W) process.stdout.write(`  ${key}: ${res.W}x${res.H} -> ${res.w}x${res.h}\n`);
  }
  await b.close();
  fs.writeFileSync(path.join(ROOT, 'js', 'asset-sizes.js'),
    '/* auto-generated by tools/optimize-assets.js: logical (original) pixel sizes [w,h,ext] of every shipped image */\nwindow.ASSET_SIZES=' + JSON.stringify(sizes) + ';\n');
  console.log(`${USED.length} images: ${(before / 1e6).toFixed(1)} MB -> ${(after / 1e6).toFixed(2)} MB`);
})();
